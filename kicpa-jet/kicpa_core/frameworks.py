def _tests(fw, kind, cur):
    """정규식으로 볼 과목(정규식이 '.*' 인 기본값 줄은 뺌)."""
    return [k for k in BS_GROUPS[(fw, kind, cur)] if _rx(fw, "BS", k) != r".*"]


def _rx(fw, sec, key):
    for k, l, lv, t, f, rx in FRAMEWORKS[fw][sec]:
        if k == key:
            return rx
    raise KeyError(key)


def map_row(fw, row):
    """TB 행 → (구역 BS · IS · MC, 과목키, 근거). row = {코드, 계정과목, 구분, 표시과목, 기말, 기초}."""
    kind = C.kind_of(row["코드"], row["계정과목"], row.get("구분"))
    c = C.cls3(row["코드"])
    disp = row.get("표시과목") or ""
    name = row.get("계정과목") or ""
    combined = "및" in disp                # '매출채권및기타채권' 같은 묶음 표시과목은 과목을 가르는 데 쓰지 않는다
    texts = [t for t in ((name,) if combined else (disp, name)) if t]
    if kind == "제조":
        for t in texts:
            for k in ("재료비", "노무비"):
                if re.search(_rx(fw, "MC", k), t):
                    return "MC", k, "계정명"
        return "MC", "경비", "기본값"
    if kind == "자산" and "대손충당금" in name:     # 대손충당금은 붙어 있는 채권을 따른다
        if c in (109, 111) or "매출" in name:
            return "BS", "매출채권", "분류 번호"
        return "BS", ("기타채권" if fw == "ifrs" else "당좌기타"), "분류 번호"
    if kind in ("자산", "부채", "자본"):
        cur = None if kind == "자본" else _current(fw, kind, c, " ".join([disp, name]))
        for t in texts:
            for k in _tests(fw, kind, cur):
                if re.search(_rx(fw, "BS", k), t):
                    return "BS", k, "표시과목" if t == disp else "계정명"
        return "BS", FALLBACK[(fw, kind, cur)], "기본값"
    if kind == "손익":
        credit = (row.get("기말") or 0) + (row.get("기초") or 0) < 0
        for t in texts:
            for k in IS_ORDER[fw]:
                if re.search(_rx(fw, "IS", k), t):
                    if k in ("매출액", "매출원가") and c is not None and c >= 800:
                        continue                    # 판관비 · 영업외 코드의 '임대료' 등은 매출로 보지 않음(표시과목이 매출이면 위에서 이미 맞음)
                    return "IS", k, "표시과목" if t == disp else "계정명"
        b = _is_bucket(fw, c, credit)
        return "IS", b, "분류 번호" if c is not None else "기본값"
    return None, None, "미분류"
