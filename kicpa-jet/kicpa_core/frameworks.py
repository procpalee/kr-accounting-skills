    if "비유동" in text or "장기" in text:
        return False
    if "유동" in text:
        return True
    if NONCUR.search(text):
        return False
    for k in _tests(fw, kind, False):                    # 비유동 과목 정규식이 맞으면 비유동
        if re.search(_rx(fw, "BS", k), text):
            return False
    for k in _tests(fw, kind, True):
        if re.search(_rx(fw, "BS", k), text):
            return True
    if c is not None:
        if kind == "자산":
            return c <= 175
        if kind == "부채":
            return c <= 290
    return True


